import assert from 'node:assert/strict';
import { calculateFinance, defaultFinance, financeEnquiry, financeUrl, validateFinance } from '../src/lib/finance.ts';
import { insuranceEnquiry, warrantyEnquiry } from '../src/lib/service-plans.ts';
const cars=[{slug:'mercedes-c220d-2023',name:'Mercedes-Benz C-Class',price:4500000,year:2023,mileage:42000}];
const base={vehicle:cars[0].slug,price:'1250000',deposit:'250000',rate:'12',months:'60'};
const result=calculateFinance(base);
assert.ok(Math.abs(result.emi-22244.44768490176)<.00001);
assert.ok(Math.abs(result.totalInterest-334666.8610941055)<.01);
assert.ok(Math.abs(result.schedule.reduce((s,r)=>s+r.principal,0)-1000000)<.01);
assert.ok(Math.abs(result.schedule.reduce((s,r)=>s+r.interest,0)-result.totalInterest)<.01);
assert.equal(result.schedule.at(-1).balance,0);
for(let i=1;i<result.schedule.length;i++) assert.ok(result.schedule[i].balance<result.schedule[i-1].balance);
const free=calculateFinance({...base,rate:'0'});
assert.equal(free.totalInterest,0);assert.equal(free.emi,1000000/60);assert.equal(free.schedule.at(-1).balance,0);
const cash=calculateFinance({...base,deposit:base.price});assert.equal(cash.emi,0);assert.equal(cash.principal,0);assert.equal(cash.totalCost,1250000);
for (const patch of [{price:''},{price:'99999'},{price:'100000001'},{price:'Infinity'},{deposit:'-1'},{deposit:'1250001'},{deposit:''},{rate:'31'},{rate:'-1'},{rate:''},{months:'13'},{months:'0'}])assert.equal(calculateFinance({...base,...patch}),null,JSON.stringify(patch));
assert.ok(validateFinance({...base,deposit:'1250001'}).deposit);
const high=calculateFinance({...base,price:'100000000',deposit:'0',months:'84',rate:'30'});assert.ok(Number.isFinite(high.emi));assert.equal(high.schedule.length,7);assert.equal(high.schedule.at(-1).balance,0);
const low=calculateFinance({...base,rate:'0.00001'});assert.ok(Number.isFinite(low.emi));assert.equal(low.schedule.at(-1).balance,0);
assert.deepEqual(defaultFinance(cars,Object.fromEntries(new URLSearchParams(financeUrl(base).split('?')[1]))),base);
assert.equal(defaultFinance(cars,{vehicle:'missing'}).vehicle,cars[0].slug);
assert.equal(defaultFinance(cars,{price:['one','two']}).price,'4500000');
assert.ok(calculateFinance(defaultFinance([])));
for (const text of ['Mercedes-Benz C-Class','Loan amount: ₹10,00,000','Term: 60 months','Estimated monthly EMI: ₹22,244'])assert.ok(financeEnquiry(base,cars).includes(text),text);
assert.ok(insuranceEnquiry(cars[0],'third-party',true).includes('Third-party cover'));
assert.ok(insuranceEnquiry(cars[0],'third-party',true).includes('Please check availability and price'));
assert.ok(warrantyEnquiry(cars[0],24,15000).includes('24 months'));
assert.ok(warrantyEnquiry(cars[0],24,15000).includes('15,000 km'));
console.log('Finance maths, amortisation, zero-rate/full-payment, bounds, URL round-trip and service enquiry checks passed.');
